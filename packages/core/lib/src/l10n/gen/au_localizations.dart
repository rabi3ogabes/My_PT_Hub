class _AuL10nDelegate extends LocalizationsDelegate<AuL10n> {
  const _AuL10nDelegate();

  @override
  Future<AuL10n> load(Locale locale) {
    return SynchronousFuture<AuL10n>(lookupAuL10n(locale));
  }

  @override
  bool isSupported(Locale locale) =>
      <String>['ar', 'en', 'es', 'fr'].contains(locale.languageCode);

  @override
  bool shouldReload(_AuL10nDelegate old) => false;
}

AuL10n lookupAuL10n(Locale locale) {
  // Lookup logic when only language code is specified.
  switch (locale.languageCode) {
    case 'ar':
      return AuL10nAr();
    case 'en':
      return AuL10nEn();
    case 'es':
      return AuL10nEs();
    case 'fr':
      return AuL10nFr();
  }

  throw FlutterError(
    'AuL10n.delegate failed to load unsupported locale "$locale". This is likely '
    'an issue with the localizations generation tool. Please file an issue '
    'on GitHub with a reproducible sample app and the gen-l10n configuration '
    'that was used.',
  );
}
